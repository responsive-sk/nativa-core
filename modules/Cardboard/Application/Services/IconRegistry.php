    /**
     * Get SVG markup for an icon key.
     *
     * Returns empty string for unknown keys (safe fallback — no icon rendered).
     */
    public static function svg(string $key): string
    {
        return self::ICONS[$key] ?? '';
    }

    /**
     * Resolve icon key for a nav item (DB icon or default mapping).
     */
    public static function resolveKey(string $itemId, ?string $dbIcon): string
    {
        if (null !== $dbIcon && '' !== $dbIcon && isset(self::ICONS[$dbIcon])) {
            return $dbIcon;
        }

        return self::DEFAULT_ICONS[$itemId] ?? '';
    }

    /**
     * Validate that an icon key exists in the registry.
     */
    public static function isValid(string $key): bool
    {
        return '' === $key || isset(self::ICONS[$key]);
    }

    /**
     * All available icon keys with their labels.
     *
     * @return list<array{key: string, label: string}>
     */
    public static function options(): array
    {
        $labels = [
            'dashboard' => 'Dashboard', 'users' => 'Users', 'shield' => 'Shield',
            'settings' => 'Settings', 'globe' => 'Globe', 'image' => 'Image',
            'file-text' => 'File Text', 'file' => 'File', 'tag' => 'Tag',
            'message' => 'Message', 'edit' => 'Edit', 'clipboard' => 'Clipboard',
            'bar-chart' => 'Bar Chart', 'bell' => 'Bell', 'link' => 'Link',
            'home' => 'Home', 'search' => 'Search', 'database' => 'Database',
            'key' => 'Key', 'lock' => 'Lock', 'folder' => 'Folder', 'rss' => 'RSS',
            'inbox' => 'Inbox',
        ];

        $options = [];
        foreach (self::ICONS as $key => $_svg) {
            $options[] = ['key' => $key, 'label' => $labels[$key]];
        }

        return $options;
    }

    /**
     * Render an <option> element for each icon.
     */
    public static function optionsHtml(string $selected = ''): string
    {
        $html = '<option value="">— none —</option>';
        foreach (self::options() as $opt) {
            $sel = $opt['key'] === $selected ? ' selected' : '';
            $label = htmlspecialchars($opt['label'], ENT_QUOTES, 'UTF-8');
            $html .= '<option value="' . $opt['key'] . '"' . $sel . '>' . $label . '</option>';
        }

        return $html;
    }
