#!/bin/bash
#
# =============================================================================
# publish-themes.sh - replace the published gallery with this tree's gallery.
# =============================================================================
# `evan70/nativa-themes` is generated output: the gallery pages, the theme
# modules their demo pages are rendered from, and the synced frontend sources.
# This is its only writer. The sequence mirrors publish-core.sh:
#
#   1. refuse a dirty source tree for a real publish, because the commit names
#      HEAD; a dry run may use the working tree, which is what it previews;
#   2. prove the gallery's `src/` matches this tree (`sync-themes.mjs --check`);
#   3. stage the gallery, re-render every generated demo page from the theme
#      modules, and copy the module catalogue;
#   4. clone the published repository and replace the gallery-managed paths;
#   5. commit only when the tree differs, naming the source commit, and push.
#
# Its `.github/`, `.gitignore`, `.npmrc` and any path this tree does not own
# stay untouched, so the published repository keeps its own workflow.
#
# Usage:
#   bin/build/publish-themes.sh --dry-run   # stage + render, print, no network
#   bin/build/publish-themes.sh --yes       # clone, replace, push
#
#   REPO=evan70/nativa-themes BRANCH=main bin/build/publish-themes.sh --yes
# =============================================================================

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
GALLERY="$ROOT/themes/gallery"
REPO="${REPO:-evan70/nativa-themes}"
BRANCH="${BRANCH:-main}"
DRY_RUN=false
CONFIRMED=false
CLEANUP=""
LABEL="publish-themes"

usage() {
    awk 'NR>1 && /^set -euo pipefail$/{exit} NR>1{print}' "$0" | sed 's/^# \?//'
}

fail() {
    echo "$LABEL: $1" >&2
    exit "${2:-1}"
}

step() {
    echo "==> $*"
}

cleanup() {
    if [ -n "$CLEANUP" ]; then
        rm -rf "$CLEANUP"
    fi
}
trap cleanup EXIT

while [ $# -gt 0 ]; do
    case "$1" in
        --dry-run) DRY_RUN=true ;;
        --yes) CONFIRMED=true ;;
        --help|-h) usage; exit 0 ;;
        *) fail "unknown argument: $1 (see --help)" ;;
    esac
    shift
done

if [ "$DRY_RUN" != true ] && [ "$CONFIRMED" != true ]; then
    fail "a real publish needs --yes (or use --dry-run to see it)" 2
fi

[ -d "$GALLERY" ] || fail "no gallery at $GALLERY" 2
[ -f "$ROOT/bin/build/render-theme-pages.php" ] || fail "no render-theme-pages.php" 2

COMMIT="$(git -C "$ROOT" rev-parse HEAD)"
SHORT="$(git -C "$ROOT" rev-parse --short HEAD)"

if [ "$DRY_RUN" != true ] && [ -n "$(git -C "$ROOT" status --porcelain)" ]; then
    fail "the source tree is dirty; commit or stash before publishing (the commit names HEAD)" 2
fi

step "Checking the gallery sources against $SHORT"
node "$GALLERY/scripts/sync-themes.mjs" --check

WORK="$(mktemp -d "${TMPDIR:-/tmp}/nativa-themes-publish.XXXXXX")"
CLEANUP="$WORK"
STAGE="$WORK/gallery"

step "Staging the gallery in $STAGE"
mkdir -p "$STAGE"
rsync -a \
    --exclude node_modules \
    --exclude dist \
    --exclude .git \
    "$GALLERY/" "$STAGE/"

step "Rendering the demo pages from the theme modules"
php "$ROOT/bin/build/render-theme-pages.php" --out="$STAGE"

files="$(find "$STAGE" -type f | wc -l | tr -d ' ')"
size="$(du -sh "$STAGE" | cut -f1)"

if [ "$DRY_RUN" = true ]; then
    step "Dry run: nothing was published"
    echo "    repository: $REPO ($BRANCH)"
    echo "    source:     $SHORT"
    echo "    gallery:    $size, $files files"
    echo "    modules:    $(find "$ROOT/modules/Themes" -maxdepth 1 -mindepth 1 -type d | wc -l | tr -d ' ') theme directories"
    echo "    next:       bin/build/publish-themes.sh --yes"
    exit 0
fi

command -v gh >/dev/null 2>&1 || fail "gh is not on PATH" 2

if gh repo view "$REPO" >/dev/null 2>&1; then
    step "Cloning $REPO"
    git clone --quiet --branch "$BRANCH" "https://github.com/$REPO.git" "$WORK/repo" 2>/dev/null \
        || { git clone --quiet "https://github.com/$REPO.git" "$WORK/repo"; git -C "$WORK/repo" checkout -B "$BRANCH"; }
else
    fail "the published gallery repository does not exist or gh cannot see it: $REPO" 2
fi

step "Replacing the gallery-managed paths"
for entry in "$STAGE"/* "$STAGE"/.[!.]*; do
    [ -e "$entry" ] || continue
    name="$(basename "$entry")"
    case "$name" in
        .github|.gitignore|.npmrc|modules) continue ;;
    esac
    rm -rf "$WORK/repo/$name"
    cp -a "$entry" "$WORK/repo/$name"
done

if [ -d "$ROOT/modules/Themes" ]; then
    mkdir -p "$WORK/repo/modules"
    rm -rf "$WORK/repo/modules/Themes"
    cp -a "$ROOT/modules/Themes" "$WORK/repo/modules/Themes"
fi

cd "$WORK/repo"

if [ -z "$(git status --porcelain)" ]; then
    step "No change: $REPO already carries this gallery"
    exit 0
fi

git add -A

git -c user.name="nativa-publisher" \
    -c user.email="nativa-publisher@users.noreply.github.com" \
    commit --quiet -m "$(cat <<EOF
chore: gallery from nativa-php-core@$SHORT

Generated by bin/build/publish-themes.sh in responsive-sk/nativa-php-core.
Source commit: $COMMIT
EOF
)"

step "Pushing $SHORT to $REPO ($BRANCH)"

# A runner has no git credential helper, so GH_TOKEN alone cannot answer the
# https prompt. The header keeps the token out of the remote URL and the log.
if [ -n "${GH_TOKEN:-}" ]; then
    auth="$(printf 'x-access-token:%s' "$GH_TOKEN" | base64 | tr -d '\n')"
    git -c http.extraheader="AUTHORIZATION: basic $auth" push --quiet origin "$BRANCH"
else
    git push --quiet origin "$BRANCH"
fi

step "Published"
echo "    repository: https://github.com/$REPO"
echo "    source:     $SHORT"
echo "    gallery:    $size, $files files"
